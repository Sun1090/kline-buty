/** 语言 → Intl locale（日期/数字格式化用） */
export function localeFor(lang: Lang): string {
  switch (lang) {
    case 'zh-CN':
      return 'zh-CN'
    case 'en':
      return 'en-US'
    case 'ja':
      return 'ja-JP'
    case 'ko':
      return 'ko-KR'
    case 'es':
      return 'es-ES'
  }
}

/** 图表渲染层（adapter）所需的本地化标签：文本标注默认文案 + 仓位线标签 */
export interface ChartLabels {
  defaultText: string
  entry: string
  tp: string
  sl: string
  /** 量度标签的 K 线根数单位（{bars} 占位） */
  measureBars: string
  /** 图表水印文案（免责声明） */
  watermark: string
}

export function chartLabelsFor(lang: Lang): ChartLabels {
  const m = DICTIONARIES[lang]
  return {
    defaultText: m.drawing.defaultText,
    entry: m.position.lineEntry,
    tp: m.position.lineTp,
    sl: m.position.lineSl,
    measureBars: m.drawing.measureBars,
    watermark: m.disclaimer.watermark,
  }
}


