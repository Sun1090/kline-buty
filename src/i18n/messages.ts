/** 语言 → Intl locale（日期/数字格式化用） */
export function localeFor(lang: Lang): string {
  switch (lang) {
    case 'zh-CN':
      return 'zh-CN'
    case 'en':
      return 'en-US'
    case 'ja':
      return 'ja-JP'
    case 'ko':
      return 'ko-KR'
    case 'es':
      return 'es-ES'
  }
}

